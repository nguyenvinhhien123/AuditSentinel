
from pathlib import Path
from datetime import datetime, timezone
import heapq
import json
import tempfile
import uuid

from src.risk_scoring import calculate_risk_score, severity_from_risk_score


class AlertManager:
    """
    Store and manage alerts generated by Detection Engine.

    Alerts are stored as JSON Lines (one JSON object per line).
    The manager does not execute response actions.
    """

    VALID_STATUSES = {
        "NEW",
        "ACKNOWLEDGED",
        "RESOLVED",
    }

    VALID_SEVERITIES = {
        "CRITICAL",
        "HIGH",
        "MEDIUM",
        "LOW",
    }

    def __init__(self, storage_path="logs/alerts.jsonl"):
        self.storage_path = Path(storage_path).resolve()
        self.storage_path.parent.mkdir(
            parents=True,
            exist_ok=True,
        )

        if not self.storage_path.exists():
            self.storage_path.touch()

    @staticmethod
    def _now():
        return datetime.now(timezone.utc).isoformat()

    @staticmethod
    def _classify_severity(result, context=None):
        verdict = result.get("verdict")
        confidence = result.get("confidence")

        risk = calculate_risk_score(
            confidence=confidence,
            anomaly_score=result.get("anomaly_score"),
            context=context,
            verdict=verdict,
        )
        severity = severity_from_risk_score(risk["risk_score"])
        if severity is not None:
            return severity

        return None

    @staticmethod
    def _enrich_alert(alert):
        enriched = dict(alert)
        risk = calculate_risk_score(
            confidence=enriched.get("confidence"),
            anomaly_score=enriched.get("anomaly_score"),
            context=enriched.get("context"),
            verdict=enriched.get("verdict"),
        )
        enriched.update(risk)
        severity = severity_from_risk_score(risk["risk_score"])
        if severity is not None:
            enriched["severity"] = severity
        return enriched

    @staticmethod
    def _safe_context(record):
        """
        Store only selected event fields.
        Avoid copying an entire potentially sensitive audit record.
        """

        if not isinstance(record, dict):
            return {}

        allowed_fields = {
            "timestamp",
            "username",
            "user",
            "src_ip",
            "source_ip",
            "client_ip",
            "sql_action",
            "action",
            "event_type",
            "status",
            "query",
            "sql",
        }

        context = {}

        for key, value in record.items():
            normalized_key = str(key).strip().lower()

            if normalized_key not in allowed_fields:
                continue

            if value is None:
                context[normalized_key] = None
            elif isinstance(value, (str, int, float, bool)):
                text_value = str(value)

                if normalized_key in {"query", "sql"}:
                    context[normalized_key] = text_value[:500]
                else:
                    context[normalized_key] = text_value[:200]

        return context

    def _iter_alerts(self):
        try:
            with self.storage_path.open(
                "r",
                encoding="utf-8",
            ) as file:
                for line_number, line in enumerate(file, start=1):
                    if not line.strip():
                        continue

                    try:
                        alert = json.loads(line)
                    except json.JSONDecodeError as exc:
                        raise ValueError(
                            f"Invalid alert JSON on line {line_number}"
                        ) from exc

                    if not isinstance(alert, dict):
                        raise ValueError(
                            f"Invalid alert record on line {line_number}"
                        )

                    yield alert

        except OSError as exc:
            raise RuntimeError(
                f"Cannot read alert storage: {exc}"
            ) from exc

    def _read_alerts(self):
        return list(self._iter_alerts())

    def _iter_alerts_reverse(self, chunk_size=64 * 1024):
        try:
            with self.storage_path.open("rb") as file:
                position = file.seek(0, 2)
                pending = b""

                while position:
                    size = min(chunk_size, position)
                    position -= size
                    file.seek(position)
                    lines = (file.read(size) + pending).split(b"\n")
                    pending = lines[0]

                    for line in reversed(lines[1:]):
                        if not line.strip():
                            continue
                        yield self._parse_alert_line(line)

                if pending.strip():
                    yield self._parse_alert_line(pending)

        except OSError as exc:
            raise RuntimeError(
                f"Cannot read alert storage: {exc}"
            ) from exc

    @staticmethod
    def _parse_alert_line(line):
        try:
            alert = json.loads(line)
        except (json.JSONDecodeError, UnicodeDecodeError) as exc:
            raise ValueError(
                "Invalid alert JSON in alert storage"
            ) from exc

        if not isinstance(alert, dict):
            raise ValueError("Invalid alert record in alert storage")

        return alert

    def _write_alerts(self, alerts):
        temporary_path = self.storage_path.with_suffix(".tmp")

        try:
            with temporary_path.open(
                "w",
                encoding="utf-8",
            ) as file:
                for alert in alerts:
                    file.write(
                        json.dumps(
                            alert,
                            ensure_ascii=False,
                        ) + "\n"
                    )

            temporary_path.replace(self.storage_path)

        finally:
            if temporary_path.exists():
                temporary_path.unlink()

    def create_alert(
        self,
        detection_result,
        model_id=None,
        model_name=None,
        record=None,
    ):
        """Create an alert from one Detection Engine result."""

        if not isinstance(detection_result, dict):
            raise TypeError("detection_result must be a dictionary")

        context = self._safe_context(record)
        severity = self._classify_severity(detection_result, context)

        if severity is None:
            return {
                "status": "NO_ALERT",
                "message": "Detection result does not require an alert",
            }

        alert = {
            "alert_id": str(uuid.uuid4()),
            "created_at": self._now(),
            "updated_at": self._now(),
            "status": "NEW",
            "severity": severity,
            "mode": detection_result.get("mode"),
            "verdict": detection_result.get("verdict"),
            "predicted_label": detection_result.get("predicted_label"),
            "confidence": detection_result.get("confidence"),
            "anomaly_score": detection_result.get("anomaly_score"),
            "record_index": detection_result.get("record_index"),
            "model_id": model_id,
            "model_name": model_name,
            "context": context,
            "resolution": None,
        }
        alert.update(calculate_risk_score(
            confidence=alert["confidence"],
            anomaly_score=alert["anomaly_score"],
            context=alert["context"],
            verdict=alert["verdict"],
        ))

        with self.storage_path.open(
            "a",
            encoding="utf-8",
        ) as file:
            file.write(
                json.dumps(
                    alert,
                    ensure_ascii=False,
                ) + "\n"
            )

        return {
            "status": "CREATED",
            "alert": alert,
        }

    def ingest_detection(self, detection_output, records=None):
        """
        Convert Detection Engine batch output into stored alerts.

        records is optional and must follow the same order as results.
        """

        if not isinstance(detection_output, dict):
            raise TypeError("detection_output must be a dictionary")

        if detection_output.get("status") != "COMPLETED":
            raise ValueError("Detection output is not completed")

        results = detection_output.get("results")

        if not isinstance(results, list):
            raise ValueError("Detection results must be a list")

        if records is not None:
            if not isinstance(records, list):
                raise TypeError("records must be a list")

            if len(records) != len(results):
                raise ValueError(
                    "records and detection results must have equal length"
                )

        created = []
        skipped = 0

        for index, result in enumerate(results):
            record = records[index] if records is not None else None

            outcome = self.create_alert(
                detection_result=result,
                model_id=detection_output.get("model_id"),
                model_name=detection_output.get("model_name"),
                record=record,
            )

            if outcome["status"] == "CREATED":
                created.append(outcome["alert"])
            else:
                skipped += 1

        return {
            "status": "COMPLETED",
            "alerts_created": len(created),
            "records_skipped": skipped,
            "alerts": created,
        }

    def list_alerts(
        self,
        severity=None,
        status=None,
        limit=100,
    ):
        """List alerts with optional filters."""

        if not isinstance(limit, int) or limit < 1:
            raise ValueError("limit must be a positive integer")

        if severity is not None:
            severity = severity.upper()

            if severity not in self.VALID_SEVERITIES:
                raise ValueError("Invalid severity filter")

        if status is not None:
            status = status.upper()

            if status not in self.VALID_STATUSES:
                raise ValueError("Invalid status filter")

        latest = []
        for index, alert in enumerate(self._iter_alerts()):
            if severity and alert.get("severity") != severity:
                continue
            if status and alert.get("status") != status:
                continue

            created_at = alert.get("created_at", "")
            entry = (created_at, -index, alert)
            if len(latest) < limit:
                heapq.heappush(latest, entry)
            elif entry[:2] > latest[0][:2]:
                heapq.heapreplace(latest, entry)

        latest.sort(key=lambda entry: entry[:2], reverse=True)
        return [self._enrich_alert(entry[2]) for entry in latest]

    def list_recent_alerts(
        self,
        severity=None,
        status=None,
        limit=100,
    ):
        """List the newest appended alerts without scanning older history."""

        if not isinstance(limit, int) or limit < 1:
            raise ValueError("limit must be a positive integer")

        if severity is not None:
            severity = severity.upper()

            if severity not in self.VALID_SEVERITIES:
                raise ValueError("Invalid severity filter")

        if status is not None:
            status = status.upper()

            if status not in self.VALID_STATUSES:
                raise ValueError("Invalid status filter")

        alerts = []
        for alert in self._iter_alerts_reverse():
            if severity and alert.get("severity") != severity:
                continue
            if status and alert.get("status") != status:
                continue

            alerts.append(alert)
            if len(alerts) == limit:
                break

        return [
            self._enrich_alert(alert)
            for alert in sorted(
                alerts,
                key=lambda alert: alert.get("created_at", ""),
                reverse=True,
            )
        ]

    def get_alert(self, alert_id):
        """Find an alert by scanning backward from the newest stored record."""

        if not isinstance(alert_id, str) or not alert_id.strip():
            raise ValueError("alert_id must be a non-empty string")

        alert_id = alert_id.strip()
        for alert in self._iter_alerts_reverse():
            if alert.get("alert_id") == alert_id:
                return self._enrich_alert(alert)

        return None

    def update_status(
        self,
        alert_id,
        new_status,
        resolution=None,
        progress_callback=None,
    ):
        """Acknowledge or resolve an existing alert."""

        new_status = str(new_status).upper()

        if new_status not in {"ACKNOWLEDGED", "RESOLVED"}:
            raise ValueError(
                "New status must be ACKNOWLEDGED or RESOLVED"
            )

        if new_status == "RESOLVED":
            if not isinstance(resolution, str) or not resolution.strip():
                raise ValueError(
                    "A resolution note is required"
                )

        try:
            total_bytes = self.storage_path.stat().st_size
            source = self.storage_path.open("r", encoding="utf-8")
        except OSError as exc:
            raise RuntimeError(
                f"Cannot read alert storage: {exc}"
            ) from exc

        temporary_path = None
        updated_alert = None
        previous_status = None
        last_progress = -1
        try:
            with source:
                with tempfile.NamedTemporaryFile(
                    mode="w",
                    encoding="utf-8",
                    dir=self.storage_path.parent,
                    prefix=f".{self.storage_path.name}.",
                    suffix=".tmp",
                    delete=False,
                ) as output:
                    temporary_path = Path(output.name)
                    line_number = 0
                    while True:
                        try:
                            line = source.readline()
                        except OSError as exc:
                            raise RuntimeError(
                                f"Cannot read alert storage: {exc}"
                            ) from exc
                        if not line:
                            break
                        line_number += 1

                        if not line.strip():
                            output.write(line)
                            continue

                        try:
                            alert = json.loads(line)
                        except json.JSONDecodeError as exc:
                            raise ValueError(
                                f"Invalid alert JSON on line {line_number}"
                            ) from exc

                        if not isinstance(alert, dict):
                            raise ValueError(
                                f"Invalid alert record on line {line_number}"
                            )

                        if (
                            updated_alert is None
                            and alert.get("alert_id") == alert_id
                        ):
                            previous_status = alert.get("status")
                            alert["status"] = new_status
                            alert["updated_at"] = self._now()
                            if new_status == "RESOLVED":
                                alert["resolution"] = resolution.strip()
                            updated_alert = alert
                            output.write(
                                json.dumps(alert, ensure_ascii=False) + "\n"
                            )
                        else:
                            output.write(line)

                        if progress_callback is not None:
                            progress = min(
                                99,
                                int(
                                    source.tell()
                                    * 100
                                    / max(total_bytes, 1)
                                ),
                            )
                            if progress != last_progress:
                                progress_callback(progress)
                                last_progress = progress

            if updated_alert is None:
                raise KeyError(f"Unknown alert ID: {alert_id}")
            if previous_status == "RESOLVED":
                raise ValueError("Resolved alerts cannot be changed")
            if (
                previous_status == "ACKNOWLEDGED"
                and new_status == "ACKNOWLEDGED"
            ):
                raise ValueError("Alert is already acknowledged")

            temporary_path.replace(self.storage_path)
            if progress_callback is not None:
                progress_callback(100)
        finally:
            if (
                temporary_path is not None
                and temporary_path.exists()
            ):
                temporary_path.unlink()

        return {
            "status": "UPDATED",
            "alert": updated_alert,
        }

    def get_statistics(self):
        """Return counts grouped by severity and status."""

        severity_counts = {
            severity: 0
            for severity in self.VALID_SEVERITIES
        }

        status_counts = {
            status: 0
            for status in self.VALID_STATUSES
        }
        total_alerts = 0

        for alert in self._iter_alerts():
            total_alerts += 1
            severity = alert.get("severity")
            status = alert.get("status")

            if severity in severity_counts:
                severity_counts[severity] += 1

            if status in status_counts:
                status_counts[status] += 1

        return {
            "total_alerts": total_alerts,
            "severity_counts": severity_counts,
            "status_counts": status_counts,
            "open_alerts": (
                status_counts["NEW"]
                + status_counts["ACKNOWLEDGED"]
            ),
        }
